#!/usr/bin/env node
/**
 * SMS Gateway v5 — local FCM HTTP v1 + Google OAuth2 stub.
 *
 * This is an *independent* offline stand-in for two Google endpoints that the
 * Worker under test calls out to:
 *
 *   POST /token                                  -> OAuth2 token exchange
 *                                                   (grant_type=jwt-bearer + RS256 assertion)
 *   POST /v1/projects/:project/messages:send     -> FCM HTTP v1 send
 *
 * Everything it saw is exposed for assertions:
 *
 *   GET  /__log          -> { requests: [...], validationErrors: [...], tokenCalls: n, sendCalls: n }
 *   POST /__log/reset    -> clears the log
 *
 * The OAuth2 assertion is structurally decoded and its RS256 signature verified
 * against the public half of the stub service account, so a malformed or
 * wrongly-signed assertion is caught here rather than silently accepted.
 *
 * The service account at test-support/stub-service-account.json is a TEST
 * FIXTURE. It is generated locally, never uploaded, and is not a real key.
 *
 * Zero runtime dependencies: node builtins only.
 *
 * Run standalone:   node test-support/fcm-stub.mjs [--port 8790]
 * Or via harness:   node sms_gateway_test_harness.mjs stub
 */
import http from 'node:http';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const DEFAULT_SERVICE_ACCOUNT_PATH = path.join(HERE, 'stub-service-account.json');
export const DEFAULT_PORT = 8790;

/**
 * Load the stub service account, generating an RSA-2048 fixture on first use.
 * The generated file is a test fixture and must never be treated as a secret.
 */
export function ensureServiceAccount(saPath = DEFAULT_SERVICE_ACCOUNT_PATH) {
  if (fs.existsSync(saPath)) {
    const raw = JSON.parse(fs.readFileSync(saPath, 'utf8'));
    if (!raw.private_key || !raw.client_email) {
      throw new Error(`${saPath} exists but is not a service-account JSON`);
    }
    return raw;
  }
  const { privateKey, publicKey } = crypto.generateKeyPairSync('rsa', {
    modulusLength: 2048,
    publicKeyEncoding: { type: 'spki', format: 'pem' },
    privateKeyEncoding: { type: 'pkcs8', format: 'pem' },
  });
  const keyId = crypto.createHash('sha1').update(publicKey).digest('hex').slice(0, 40);
  const sa = {
    _comment:
      'TEST FIXTURE ONLY — generated by test-support/fcm-stub.mjs. NOT a real Google key. Never use outside the local harness.',
    type: 'service_account',
    project_id: 'sms-gateway-stub',
    private_key_id: keyId,
    private_key: privateKey,
    client_email: 'stub-harness@sms-gateway-stub.iam.gserviceaccount.com',
    client_id: '100000000000000000001',
    auth_uri: 'https://accounts.google.com/o/oauth2/auth',
    token_uri: 'https://oauth2.googleapis.com/token',
    auth_provider_x509_cert_url: 'https://www.googleapis.com/oauth2/v1/certs',
    client_x509_cert_url:
      'https://www.googleapis.com/robot/v1/metadata/x509/stub-harness%40sms-gateway-stub.iam.gserviceaccount.com',
    universe_domain: 'googleapis.com',
  };
  fs.mkdirSync(path.dirname(saPath), { recursive: true });
  fs.writeFileSync(saPath, JSON.stringify(sa, null, 2) + '\n');
  return sa;
}

function b64urlJson(part) {
  return JSON.parse(Buffer.from(part, 'base64url').toString('utf8'));
}

/**
 * Structural + cryptographic validation of the OAuth2 JWT bearer assertion.
 * Returns null when acceptable, or a human-readable reason when not.
 */
export function validateAssertion(jwt, serviceAccount) {
  if (typeof jwt !== 'string' || !jwt) return 'missing assertion';
  const parts = jwt.split('.');
  if (parts.length !== 3) return `assertion is not a three-part JWT (got ${parts.length} parts)`;

  let header;
  let claims;
  try {
    header = b64urlJson(parts[0]);
    claims = b64urlJson(parts[1]);
  } catch (e) {
    return `assertion header/claims are not base64url JSON: ${e.message}`;
  }

  if (header.alg !== 'RS256') return `header.alg must be RS256, got ${JSON.stringify(header.alg)}`;
  if (!header.typ && !header.kid) {
    // typ/kid are optional in practice; recorded only, not fatal.
  }

  let publicKey;
  try {
    publicKey = crypto.createPublicKey(serviceAccount.private_key);
  } catch (e) {
    return `stub service account private_key is unusable: ${e.message}`;
  }
  const signingInput = Buffer.from(`${parts[0]}.${parts[1]}`, 'utf8');
  const signature = Buffer.from(parts[2], 'base64url');
  let verified = false;
  try {
    verified = crypto.verify('sha256', signingInput, publicKey, signature);
  } catch (e) {
    return `RS256 verify threw: ${e.message}`;
  }
  if (!verified) return 'RS256 signature does not verify against the stub service-account public key';

  if (typeof claims.iss !== 'string' || !claims.iss) return 'claim iss is missing';
  if (claims.iss !== serviceAccount.client_email) {
    return `claim iss (${claims.iss}) != service account client_email (${serviceAccount.client_email})`;
  }
  if (typeof claims.scope !== 'string' || !claims.scope) return 'claim scope is missing';
  if (!/firebase\.messaging|cloud-platform/.test(claims.scope)) {
    return `claim scope lacks firebase.messaging: ${claims.scope}`;
  }
  if (typeof claims.aud !== 'string' || !claims.aud) return 'claim aud is missing';
  if (typeof claims.exp !== 'number' || !Number.isFinite(claims.exp)) return 'claim exp is missing or not a number';
  const nowS = Math.floor(Date.now() / 1000);
  if (claims.exp < nowS - 60) return `claim exp is in the past (exp=${claims.exp}, now=${nowS})`;
  if (typeof claims.iat === 'number' && claims.iat > nowS + 300) {
    return `claim iat is more than 5 minutes in the future (iat=${claims.iat})`;
  }
  return null;
}

function readBody(req) {
  return new Promise((resolve, reject) => {
    const chunks = [];
    req.on('data', (c) => chunks.push(c));
    req.on('end', () => resolve(Buffer.concat(chunks)));
    req.on('error', reject);
  });
}

function sendJson(res, status, obj) {
  const body = Buffer.from(JSON.stringify(obj, null, 2));
  res.writeHead(status, {
    'content-type': 'application/json; charset=utf-8',
    'content-length': String(body.length),
  });
  res.end(body);
}

export function createFcmStub({ serviceAccount, port = DEFAULT_PORT }) {
  const sa = serviceAccount ?? ensureServiceAccount();
  const log = { requests: [], validationErrors: [], tokenCalls: 0, sendCalls: 0, sendCounter: 0 };

  const server = http.createServer(async (req, res) => {
    const url = new URL(req.url, 'http://127.0.0.1');
    const pathname = url.pathname;
    const raw = await readBody(req);
    const entry = {
      at: new Date().toISOString(),
      method: req.method,
      path: pathname,
      query: url.search,
      headers: Object.fromEntries(Object.entries(req.headers)),
      body: raw.length ? safeJson(raw.toString('utf8')) ?? raw.toString('utf8') : null,
    };
    log.requests.push(entry);

    // ---- assertions surface -------------------------------------------------
    if (req.method === 'GET' && pathname === '/__log') {
      return sendJson(res, 200, log);
    }
    if (req.method === 'POST' && pathname === '/__log/reset') {
      log.requests = [];
      log.validationErrors = [];
      log.tokenCalls = 0;
      log.sendCalls = 0;
      log.sendCounter = 0;
      entry.body = null;
      return sendJson(res, 200, { ok: true });
    }

    // ---- OAuth2 token endpoint ---------------------------------------------
    if (req.method === 'POST' && (pathname === '/token' || pathname === '/oauth2/token' || pathname === '/o/oauth2/token')) {
      log.tokenCalls += 1;
      const text = raw.toString('utf8');
      let assertion = null;
      let grantType = null;
      const contentType = String(req.headers['content-type'] ?? '');
      if (contentType.includes('application/json')) {
        try {
          const j = JSON.parse(text || '{}');
          assertion = j.assertion ?? null;
          grantType = j.grant_type ?? null;
        } catch (e) {
          return rejectToken(res, log, entry, `token body is not valid JSON: ${e.message}`);
        }
      } else {
        const form = new URLSearchParams(text);
        assertion = form.get('assertion');
        grantType = form.get('grant_type');
      }
      if (grantType && !/jwt-bearer|refresh_token/.test(grantType)) {
        return rejectToken(res, log, entry, `unsupported grant_type ${grantType}`);
      }
      if (!assertion) {
        return rejectToken(res, log, entry, 'missing assertion parameter');
      }
      const reason = validateAssertion(assertion, sa);
      if (reason) return rejectToken(res, log, entry, reason);

      entry.assertion = decodeAssertion(assertion, sa);
      return sendJson(res, 200, {
        access_token: 'stub-access-token',
        expires_in: 3600,
        token_type: 'Bearer',
      });
    }

    // ---- FCM HTTP v1 send ---------------------------------------------------
    const sendMatch = /^\/v1\/projects\/([^/]+)\/messages:send$/.exec(pathname);
    if (req.method === 'POST' && sendMatch) {
      log.sendCalls += 1;
      const auth = String(req.headers['authorization'] ?? '');
      if (auth !== 'Bearer stub-access-token') {
        return sendJson(res, 401, {
          error: { code: 401, message: 'UNAUTHENTICATED', status: 'UNAUTHENTICATED', details: [{ reason: `expected Bearer stub-access-token, got ${JSON.stringify(auth)}` }] },
        });
      }
      let message = null;
      try {
        const j = JSON.parse(raw.toString('utf8') || '{}');
        message = j.message ?? null;
      } catch (e) {
        return sendJson(res, 400, { error: { code: 400, message: `malformed FCM body: ${e.message}` } });
      }
      if (!message || typeof message !== 'object') {
        return sendJson(res, 400, { error: { code: 400, message: 'FCM body must carry a message object' } });
      }
      if (!message.token && !message.topic && !message.condition) {
        return sendJson(res, 400, { error: { code: 400, message: 'message must target token, topic or condition' } });
      }
      log.sendCounter += 1;
      entry.project = sendMatch[1];
      return sendJson(res, 200, { name: `projects/stub/messages/${log.sendCounter}` });
    }

    return sendJson(res, 404, { error: { code: 404, message: `no stub route for ${req.method} ${pathname}` } });
  });

  return {
    server,
    log,
    port,
    url: `http://127.0.0.1:${port}`,
    listen() {
      return new Promise((resolve, reject) => {
        server.once('error', reject);
        server.listen(port, '127.0.0.1', () => {
          server.removeListener('error', reject);
          resolve(port);
        });
      });
    },
    close() {
      return new Promise((resolve) => server.close(() => resolve()));
    },
  };
}

function rejectToken(res, log, entry, reason) {
  log.validationErrors.push({ at: new Date().toISOString(), path: entry.path, reason });
  entry.validationError = reason;
  return sendJson(res, 400, { error: 'invalid_grant', error_description: reason });
}

function decodeAssertion(jwt, sa) {
  try {
    const [h, c] = jwt.split('.');
    const header = b64urlJson(h);
    const claims = b64urlJson(c);
    return {
      alg: header.alg,
      kid: header.kid ?? null,
      iss: claims.iss,
      scope: claims.scope,
      aud: claims.aud,
      exp: claims.exp,
      iat: claims.iat ?? null,
      issMatches: claims.iss === sa.client_email,
    };
  } catch (e) {
    return { decodeError: e.message };
  }
}

function safeJson(text) {
  try {
    return JSON.parse(text);
  } catch {
    return null;
  }
}

export async function startFcmStub({ port = DEFAULT_PORT, serviceAccountPath } = {}) {
  const serviceAccount = ensureServiceAccount(serviceAccountPath ?? DEFAULT_SERVICE_ACCOUNT_PATH);
  const stub = createFcmStub({ serviceAccount, port });
  await stub.listen();
  return stub;
}

function isMain() {
  const entry = process.argv[1];
  if (!entry) return false;
  try {
    return path.resolve(entry) === path.resolve(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (isMain()) {
  const portArgIndex = process.argv.indexOf('--port');
  const port = portArgIndex >= 0 ? Number(process.argv[portArgIndex + 1]) : Number(process.env.FCM_STUB_PORT ?? DEFAULT_PORT);
  const stub = await startFcmStub({ port });
  const sa = ensureServiceAccount();
  console.log(`[fcm-stub] listening on ${stub.url}`);
  console.log(`[fcm-stub] service account: ${DEFAULT_SERVICE_ACCOUNT_PATH}`);
  console.log(`[fcm-stub]   client_email = ${sa.client_email}`);
  console.log(`[fcm-stub]   POST /token and POST /v1/projects/*/messages:send are live`);
  console.log(`[fcm-stub]   GET ${stub.url}/__log   POST ${stub.url}/__log/reset`);
  const shutdown = async () => {
    await stub.close();
    process.exit(0);
  };
  process.on('SIGINT', shutdown);
  process.on('SIGTERM', shutdown);
}
