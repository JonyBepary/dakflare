-- SMS Gateway v5 — reply delivery state in the operator log.
--
-- `messages` has always stored an outbound mirror row (`direction = 'out'`), but
-- no field said what the radio did with it. A reply the phone refused therefore
-- looked exactly like a queued one: the console could not tell "sent" from
-- "delivered" from "failed", and a refused automation reply looked unanswered.
--
--   reply_state  One of 'queued', 'sent', 'failed', 'delivered', or NULL for a
--                row that predates device state reporting (and for every inbound
--                row, which has no send state). Validated at the ingest edge, not
--                with a SQL CHECK: an older Worker must still be able to read a
--                row written by a newer one, and a bad value must be a
--                `bad_request`, not a storage fault.
--
--   reply_error  The radio/deployment error for a `failed` state, capped at 200
--                characters at ingest. NULL when there is no error to report.
--
-- Both columns are additive and nullable, so every existing row keeps its
-- current meaning and a batch from a client that does not report state still
-- inserts exactly as before.
ALTER TABLE messages ADD COLUMN reply_state TEXT;
ALTER TABLE messages ADD COLUMN reply_error TEXT;
