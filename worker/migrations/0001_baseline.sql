-- DakFlare schema, baseline.
--
-- This one file replaces migrations 0001 through 0011. It is not a rewrite: it is
-- the schema those eleven steps produce, dumped from a deployment that has run
-- all of them, so a fresh install ends up with the same tables and indexes.
--
-- A deployment that already ran 0001-0011 records this file in `d1_migrations`
-- instead of applying it. `scripts/verify-baseline.sh` proves the two agree by
-- migrating a scratch database from this file and diffing `sqlite_master`
-- against production; an empty diff means the baseline is correct.
--
-- Changing the schema means adding 0002_*.sql. Do not edit this file once it has
-- been applied anywhere.

CREATE TABLE account (
  id                     text PRIMARY KEY NOT NULL,
  "accountId"            text NOT NULL,
  "providerId"           text NOT NULL,
  "userId"               text NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
  "accessToken"          text,
  "refreshToken"         text,
  "idToken"              text,
  "accessTokenExpiresAt" date,
  "refreshTokenExpiresAt" date,
  scope                  text,
  password               text,
  "createdAt"            date NOT NULL,
  "updatedAt"            date NOT NULL
);

CREATE TABLE alerts (
  id              TEXT PRIMARY KEY NOT NULL,
  device_id       TEXT NOT NULL,
  kind            TEXT NOT NULL,
  raised_at       INTEGER NOT NULL,
  acknowledged_at INTEGER,
  detail          TEXT
, resolved_at INTEGER);

CREATE TABLE audit_log (
  id          text PRIMARY KEY NOT NULL,
  at          integer NOT NULL,
  actor_user  text,
  actor_label text,
  action      text NOT NULL,
  subject     text,
  ip          text,
  user_agent  text,
  detail_json text
);

CREATE TABLE devices (
  device_id  TEXT PRIMARY KEY,
  public_key TEXT NOT NULL,
  fcm_token  TEXT,
  paired_at  INTEGER NOT NULL,
  last_seen  INTEGER NOT NULL
, label TEXT, sim_slot INTEGER, archived_at INTEGER);

CREATE TABLE flow_runs (
  device_id    TEXT NOT NULL,
  local_id     TEXT NOT NULL,
  flow_id      TEXT NOT NULL,
  flow_version INTEGER NOT NULL,
  outcome      TEXT NOT NULL,
  created_at   INTEGER NOT NULL,
  PRIMARY KEY (device_id, local_id, flow_id, flow_version)
);

CREATE TABLE invite (
  id         text PRIMARY KEY NOT NULL,
  email      text NOT NULL,
  role       text NOT NULL,
  token_hash text NOT NULL UNIQUE,
  expires_at integer NOT NULL,
  used_at    integer,
  created_by text,
  created_at integer NOT NULL
);

CREATE TABLE magic_link (
  id         text PRIMARY KEY NOT NULL,
  email      text NOT NULL,
  token_hash text NOT NULL UNIQUE,
  expires_at integer NOT NULL,
  used_at    integer,
  created_at integer NOT NULL,
  ip         text
);

CREATE TABLE messages (
  id          TEXT PRIMARY KEY NOT NULL,
  device_id   TEXT NOT NULL,
  local_id    TEXT NOT NULL,
  direction   TEXT NOT NULL CHECK (direction IN ('in', 'out')),
  peer        TEXT NOT NULL,
  body        TEXT NOT NULL,
  received_at INTEGER NOT NULL,
  auto_reply  INTEGER NOT NULL DEFAULT 0, reply_source TEXT, reply_ref TEXT, reply_command_id TEXT, reply_state TEXT, reply_error TEXT,
  UNIQUE(device_id, local_id)
);

CREATE TABLE pairing_codes (
  code       TEXT PRIMARY KEY,
  expires_at INTEGER NOT NULL
, device_id TEXT, purpose TEXT NOT NULL DEFAULT 'enroll', claimed_at INTEGER);

CREATE TABLE passkey (
  id             text PRIMARY KEY NOT NULL,
  name           text,
  "publicKey"    text NOT NULL,
  "userId"       text NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
  "credentialID" text NOT NULL,
  counter        integer NOT NULL DEFAULT 0,
  "deviceType"   text NOT NULL,
  "backedUp"     integer NOT NULL DEFAULT 0,
  transports     text,
  "createdAt"    date,
  aaguid         text
);

CREATE TABLE rule_hits (
  rule_id    TEXT NOT NULL,
  device_id  TEXT NOT NULL,
  replied_at INTEGER NOT NULL
);

CREATE TABLE rules (
  id              TEXT PRIMARY KEY NOT NULL,
  name            TEXT NOT NULL,
  enabled         INTEGER NOT NULL DEFAULT 1,
  priority        INTEGER NOT NULL DEFAULT 0,
  matcher_type    TEXT NOT NULL,
  matcher_value   TEXT NOT NULL,
  body_type       TEXT NOT NULL,
  body_value      TEXT NOT NULL,
  reply_template  TEXT NOT NULL,
  cooldown_s      INTEGER NOT NULL DEFAULT 60,
  max_per_hour    INTEGER NOT NULL DEFAULT 10,
  sim_slot        INTEGER NOT NULL DEFAULT 0,
  allow_shortcode INTEGER NOT NULL DEFAULT 0,
  device_id       TEXT,
  updated_at      INTEGER NOT NULL
);

CREATE TABLE session (
  id          text PRIMARY KEY NOT NULL,
  "expiresAt" date NOT NULL,
  token       text NOT NULL UNIQUE,
  "createdAt" date NOT NULL,
  "updatedAt" date NOT NULL,
  "ipAddress" text,
  "userAgent" text,
  "userId"    text NOT NULL REFERENCES "user"(id) ON DELETE CASCADE
);

CREATE TABLE "twoFactor" (
  id                       text PRIMARY KEY NOT NULL,
  secret                   text NOT NULL,
  "backupCodes"            text NOT NULL,
  "userId"                 text NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
  verified                 integer DEFAULT 1,
  "failedVerificationCount" integer DEFAULT 0,
  "lockedUntil"            date
);

CREATE TABLE "user" (
  id               text PRIMARY KEY NOT NULL,
  name             text NOT NULL,
  email            text NOT NULL UNIQUE,
  "emailVerified"  integer NOT NULL DEFAULT 0,
  image            text,
  "createdAt"      date NOT NULL,
  "updatedAt"      date NOT NULL,
  "twoFactorEnabled" integer NOT NULL DEFAULT 0,
  role             text
);

CREATE TABLE verification (
  id         text PRIMARY KEY NOT NULL,
  identifier text NOT NULL,
  value      text NOT NULL,
  "expiresAt" date NOT NULL,
  "createdAt" date NOT NULL,
  "updatedAt" date NOT NULL
);

CREATE TABLE workflows (
  id         TEXT PRIMARY KEY,
  name       TEXT NOT NULL,
  enabled    INTEGER NOT NULL DEFAULT 1,
  device_id  TEXT,
  graph      TEXT NOT NULL,
  version    INTEGER NOT NULL DEFAULT 1,
  created_at INTEGER NOT NULL,
  updated_at INTEGER NOT NULL
);

CREATE INDEX idx_account_user ON account("userId");

CREATE UNIQUE INDEX idx_alerts_open
  ON alerts(device_id, kind) WHERE acknowledged_at IS NULL AND resolved_at IS NULL;

CREATE INDEX idx_alerts_raised ON alerts(raised_at DESC);

CREATE INDEX idx_alerts_unresolved
  ON alerts(device_id, kind) WHERE resolved_at IS NULL;

CREATE INDEX idx_audit_action ON audit_log(action, at DESC);

CREATE INDEX idx_audit_actor ON audit_log(actor_user, at DESC);

CREATE INDEX idx_audit_at ON audit_log(at DESC);

CREATE INDEX idx_flow_runs_device ON flow_runs(device_id, created_at);

CREATE INDEX idx_invite_email ON invite(email, used_at);

CREATE INDEX idx_invite_expiry ON invite(expires_at);

CREATE INDEX idx_magic_link_email ON magic_link(email, created_at DESC);

CREATE INDEX idx_magic_link_expiry ON magic_link(expires_at);

CREATE INDEX idx_messages_device ON messages(device_id, received_at DESC);

CREATE INDEX idx_messages_direction ON messages(device_id, direction, received_at DESC);

CREATE INDEX idx_messages_received ON messages(received_at);

CREATE INDEX idx_pairing_expires ON pairing_codes(expires_at);

CREATE INDEX idx_passkey_credential ON passkey("credentialID");

CREATE INDEX idx_passkey_user ON passkey("userId");

CREATE INDEX idx_rule_hits_device ON rule_hits(device_id, replied_at);

CREATE INDEX idx_rule_hits_rule ON rule_hits(rule_id, device_id, replied_at);

CREATE INDEX idx_rules_device ON rules(device_id, enabled, priority DESC);

CREATE INDEX idx_rules_enabled ON rules(enabled, priority DESC);

CREATE INDEX idx_session_user ON session("userId");

CREATE INDEX idx_twofactor_secret ON "twoFactor"(secret);

CREATE INDEX idx_twofactor_user ON "twoFactor"("userId");

CREATE INDEX idx_verification_identifier ON verification(identifier);

CREATE INDEX idx_workflows_device ON workflows(device_id, enabled);
