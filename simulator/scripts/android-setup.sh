#!/usr/bin/env bash
#
# Install the Android build toolchain WITHOUT sudo.
#
# Everything goes under $HOME:
#   ~/.local/opt/jdk-17          Temurin JDK 17 (portable)
#   ~/Android/Sdk                cmdline-tools, platform 35, build-tools, NDK 27
#
# Requires ~6 GB free. Pass --force to run anyway.
#
#   simulator/scripts/android-setup.sh
#   source ~/.config/dakflare/android-env.sh
#
set -euo pipefail

# rustup/cargo usually live in ~/.cargo/bin, which a non-login shell may not
# have on PATH (this bit the first run).
[ -d "$HOME/.cargo/bin" ] && export PATH="$HOME/.cargo/bin:$PATH"

SDK_ROOT="${ANDROID_HOME:-$HOME/Android/Sdk}"
JDK_ROOT="$HOME/.local/opt"
NDK_MAJOR=27
REQUIRED_GB=6
ENV_FILE="$HOME/.config/dakflare/android-env.sh"

say() { printf '\n\033[1m== %s\033[0m\n' "$*"; }

if [ "${1:-}" != "--force" ]; then
  avail_kb=$(df -Pk "$HOME" | awk 'NR==2 { print $4 }')
  avail_gb=$(( avail_kb / 1024 / 1024 ))
  if [ "$avail_gb" -lt "$REQUIRED_GB" ]; then
    echo "Need about ${REQUIRED_GB} GB free; ${avail_gb} GB available under $HOME." >&2
    echo "Free some space, or re-run with --force." >&2
    exit 1
  fi
fi

unzip_to() { # unzip_to <zip> <dest>
  if command -v unzip >/dev/null 2>&1; then
    unzip -q "$1" -d "$2"
  else
    python3 -m zipfile -e "$1" "$2"
  fi
}

say "JDK 17 (portable, no sudo)"
if [ -x "$JDK_ROOT/jdk-17/bin/javac" ]; then
  echo "already installed: $JDK_ROOT/jdk-17"
else
  mkdir -p "$JDK_ROOT"
  tmp=$(mktemp -d)
  trap 'rm -rf "$tmp"' EXIT
  curl -fL --retry 3 --retry-delay 2 \
    -o "$tmp/jdk.tar.gz" \
    "https://api.adoptium.net/v3/binary/latest/17/ga/linux/x64/jdk/hotspot/normal/eclipse?project=jdk"
  tar -xzf "$tmp/jdk.tar.gz" -C "$JDK_ROOT"
  extracted=$(find "$JDK_ROOT" -maxdepth 1 -type d -name 'jdk-17*' | head -1)
  [ -n "$extracted" ] || { echo "could not find the extracted JDK" >&2; exit 1; }
  ln -sfn "$extracted" "$JDK_ROOT/jdk-17"
  rm -rf "$tmp"
  trap - EXIT
  echo "installed $JDK_ROOT/jdk-17"
fi

export JAVA_HOME="$JDK_ROOT/jdk-17"
export PATH="$JAVA_HOME/bin:$PATH"

say "Android cmdline-tools"
SDKMANAGER="$SDK_ROOT/cmdline-tools/latest/bin/sdkmanager"
if [ -x "$SDKMANAGER" ]; then
  echo "already installed: $SDKMANAGER"
else
  mkdir -p "$SDK_ROOT/cmdline-tools"
  tmp=$(mktemp -d)
  trap 'rm -rf "$tmp"' EXIT
  curl -fL --retry 3 --retry-delay 2 \
    -o "$tmp/tools.zip" \
    "https://dl.google.com/android/repository/commandlinetools-linux-11076708_latest.zip"
  unzip_to "$tmp/tools.zip" "$tmp"
  rm -rf "$SDK_ROOT/cmdline-tools/latest"
  mv "$tmp/cmdline-tools" "$SDK_ROOT/cmdline-tools/latest"
  rm -rf "$tmp"
  trap - EXIT
  echo "installed $SDKMANAGER"
fi

export ANDROID_HOME="$SDK_ROOT"
export ANDROID_SDK_ROOT="$SDK_ROOT"
export PATH="$SDK_ROOT/cmdline-tools/latest/bin:$SDK_ROOT/platform-tools:$PATH"

say "SDK licences"
yes | sdkmanager --licenses >/dev/null || true

say "SDK packages"
# Discover the newest 27.x NDK rather than pinning a version that may be gone.
NDK_ID=$(sdkmanager --list 2>/dev/null | grep -oE "ndk;${NDK_MAJOR}\.[0-9.]+" | sort -V | tail -1)
if [ -z "$NDK_ID" ]; then
  echo "no ${NDK_MAJOR}.x NDK found in the repository index" >&2
  exit 1
fi
echo "NDK: $NDK_ID"
sdkmanager --install \
  "platform-tools" \
  "platforms;android-35" \
  "build-tools;35.0.0" \
  "$NDK_ID"

NDK_PATH="$SDK_ROOT/ndk/${NDK_ID#ndk;}"

say "Rust Android targets"
rustup target add \
  aarch64-linux-android \
  armv7-linux-androideabi \
  i686-linux-android \
  x86_64-linux-android

say "Environment"
mkdir -p "$(dirname "$ENV_FILE")"
cat > "$ENV_FILE" <<EOF
# Generated by simulator/scripts/android-setup.sh
export JAVA_HOME="$JDK_ROOT/jdk-17"
export ANDROID_HOME="$SDK_ROOT"
export ANDROID_SDK_ROOT="$SDK_ROOT"
export NDK_HOME="$NDK_PATH"
export PATH="\$JAVA_HOME/bin:\$ANDROID_HOME/cmdline-tools/latest/bin:\$ANDROID_HOME/platform-tools:\$HOME/.cargo/bin:\$PATH"
EOF

echo "wrote $ENV_FILE"
echo
echo "Next:"
echo "  source $ENV_FILE"
echo "  adb connect <phone-ip>:<debug-port>     # enables wireless debugging"
echo "  cd simulator && npm run tauri android init"
echo "  npm run tauri android dev"
